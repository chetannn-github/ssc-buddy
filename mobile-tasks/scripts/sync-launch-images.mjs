import { readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const files = (await readdir(join(root, "assets", "avatars"), { withFileTypes: true }))
  .filter(entry => entry.isFile() && /\.(jpe?g|png|webp|gif)$/i.test(entry.name))
  .map(entry => entry.name).sort();
if (!files.length) throw new Error("Add at least one motivational image to assets/avatars.");
const source = "// Generated by scripts/sync-launch-images.mjs. Do not edit manually.\nexport const launchImages: number[] = [\n" +
  files.map(file => `  require(${JSON.stringify("../../assets/avatars/" + file)}),`).join("\n") + "\n];\n";
await writeFile(join(root, "src", "lib", "launch-images.ts"), source);
console.log(`Launch images synced: ${files.length}`);
