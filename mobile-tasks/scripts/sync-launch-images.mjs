import { readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const files = (await readdir(join(root, "assets", "avatars"), { withFileTypes: true }))
  .filter(entry => entry.isFile() && /\.(jpe?g|png|webp|gif)$/i.test(entry.name))
  .map(entry => entry.name).sort();
const entries = files.map(file => `  ${JSON.stringify(file)}: require(${JSON.stringify("../../assets/avatars/" + file)}),`);
if (!entries.length) entries.push('  "__default": require("../../assets/auth.jpg"),');
const source = "// Generated by scripts/sync-launch-images.mjs. Do not edit manually.\nexport const avatarAssets: Record<string, number> = {\n" +
  entries.join("\n") + "\n};\nexport const launchImages = Object.values(avatarAssets);\n";
await writeFile(join(root, "src", "lib", "launch-images.ts"), source);
console.log(`Launch images synced: ${files.length}`);
