const fs = require("node:fs");
const path = require("node:path");

function syncLaunchImages(projectRoot = path.resolve(__dirname, "..")) {
  const shared = path.resolve(projectRoot, "..", "public", "avatars");
  const bundled = path.join(projectRoot, "assets", "avatars");
  const snapshot = path.join(bundled, ".launch-images.json");
  const image = /\.(jpe?g|png|webp|gif|avif)$/i;
  fs.mkdirSync(bundled, { recursive: true });
  let files;
  if (fs.existsSync(shared)) {
    files = fs.readdirSync(shared, { withFileTypes: true })
      .filter(entry => entry.isFile() && image.test(entry.name)).map(entry => entry.name).sort();
    for (const file of files) {
      const target = path.join(bundled, file);
      const bytes = fs.readFileSync(path.join(shared, file));
      if (!fs.existsSync(target) || !fs.readFileSync(target).equals(bytes)) fs.writeFileSync(target, bytes);
    }
    // EAS archives may contain only mobile-tasks. Keep the exact shared selection
    // with the copied assets, so the remote build doesn't re-add deleted avatars.
    fs.writeFileSync(snapshot, JSON.stringify(files, null, 2) + "\n");
  } else if (fs.existsSync(snapshot)) {
    files = JSON.parse(fs.readFileSync(snapshot, "utf8"));
    if (!Array.isArray(files)) throw new Error("Invalid launch image snapshot");
    files = files.filter(file => typeof file === "string" && path.basename(file) === file && image.test(file));
    for (const file of files) if (!fs.existsSync(path.join(bundled, file))) throw new Error(`Missing bundled image: ${file}`);
  } else {
    files = fs.readdirSync(bundled, { withFileTypes: true })
      .filter(entry => entry.isFile() && image.test(entry.name)).map(entry => entry.name).sort();
  }
  const entries = files.map(file => `  ${JSON.stringify(file)}: require(${JSON.stringify("../../assets/avatars/" + file)}),`);
  if (!entries.length) entries.push('  "__default": require("../../assets/auth.jpg"),');
  const source = "// Generated by scripts/sync-launch-images.mjs. Do not edit manually.\nexport const avatarAssets: Record<string, number> = {\n" +
    entries.join("\n") + "\n};\nexport const launchImages = Object.values(avatarAssets);\n";
  const generated = path.join(projectRoot, "src", "lib", "launch-images.ts");
  fs.mkdirSync(path.dirname(generated), { recursive: true });
  if (!fs.existsSync(generated) || fs.readFileSync(generated, "utf8") !== source) fs.writeFileSync(generated, source);
  return files;
}
module.exports = { syncLaunchImages };
