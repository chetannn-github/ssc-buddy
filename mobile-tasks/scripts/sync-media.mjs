import { mkdir, readdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";

const projectRoot = process.cwd();
const assetRoot = join(projectRoot, "assets");
const generatedFile = join(projectRoot, "src", "lib", "generated-media.ts");
const extensions = {
  music: /\.(mp3|m4a|ogg|wav)$/i,
  videos: /\.(m4v|mov|mp4|ogv|webm)$/i,
};

async function listFiles(directory) {
  if (!existsSync(directory)) return [];
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return (await listFiles(path)).map((file) => join(entry.name, file));
    return entry.isFile() ? [entry.name] : [];
  }));
  return nested.flat();
}

async function syncKind(kind) {
  const source = join(assetRoot, kind);
  return (await listFiles(source))
    .filter((file) => extensions[kind].test(file))
    .map((file) => file.replaceAll("\\", "/"))
    .sort((left, right) => left.localeCompare(right));
}

const [musicTracks, videoTracks] = await Promise.all([syncKind("music"), syncKind("videos")]);
const assetImport = (kind, file) => `  ${JSON.stringify(file)}: require(${JSON.stringify(`../../assets/${kind}/${file}`)}),`;
const source = `// Generated by scripts/sync-media.mjs. Do not edit manually.\n\nexport const musicTracks = ${JSON.stringify(musicTracks, null, 2)} as string[];\nexport const videoTracks = ${JSON.stringify(videoTracks, null, 2)} as string[];\n\nexport const bundledMusic: Record<string, number> = {\n${musicTracks.map((file) => assetImport("music", file)).join("\n")}\n};\n\nexport const bundledVideos: Record<string, number> = {\n${videoTracks.map((file) => assetImport("videos", file)).join("\n")}\n};\n`;
await mkdir(dirname(generatedFile), { recursive: true });
await writeFile(generatedFile, source);
console.log(`SSC Buddy media synced: ${videoTracks.length} reels, ${musicTracks.length} audio tracks.`);
